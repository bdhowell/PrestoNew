"""Extract document text and visual elements with Docling for IBM watsonx.

Requires Python 3.10+ and: pip install 'docling==2.133.0'
Uses DoclingServiceClient, the official async-job-aware service client. Supply
DOCLING_SERVICE_URL and DOCLING_SERVICE_API_KEY from your Docling service
(not the watsonx foundation-model endpoint or an IAM bearer token).

Example:
    from docling_watsonx_extractor import extract_document
    result = extract_document('paper.pdf', output_dir='extracted')
    for item in result['elements']:
        print(item['id'], item['kind'], item['asset'], item['caption_refs'])

Inputs: local paths, bytes, or binary streams. Bytes/streams require filename.
Outputs: JSON-compatible dict, extraction.json, full Docling document JSON,
text with inline element markers, and picture/table/formula crops where
available. PDF pictures are stored as SVG when their cropped page content is
pure vector, otherwise as PNG rendered from the PDF at native resolution
(VECTOR_RENDER_DPI for formulas, tables and other vector content). All output asset paths are relative to output_dir. Each call creates
a separate run directory. Element IDs are Docling JSON pointers scoped to that
run. The full document retains original text, hierarchy, provenance, annotations,
chart data and native references.

iWork files are submitted directly to the configured Docling service.
Service support depends on its version; unsupported conversions fail explicitly.
Supply a pdf_exporter callback with render_office=True to render DOCX/PPTX/XLSX:
    def exporter(source: Path, destination: Path) -> Path: ...
The callback must return a real PDF; this is useful when visual math matters.
Native Office conversion preserves structure but may omit rendered drawings.

Extraction is best effort. A rendered chart is a picture; chart data remains in
annotations if Docling recognizes it. Formula text/LaTeX is model output, not a
guarantee of faithful symbolic reconstruction. Explicit Docling links are kept;
numbered textual mentions are separate, marked heuristic, and can be ambiguous.
No nearby-paragraph association or missing chart values are invented. PDF export
can change pagination and sheet layout; provenance then refers to that PDF.
No source document or API key is saved by this module.

CLI: python docling_watsonx_extractor.py input.pdf --output extracted
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
import os
import re
import subprocess
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path
from typing import Any, BinaryIO
from collections.abc import Callable
from uuid import uuid4

import ctypes

import pypdfium2 as pdfium
import pypdfium2.raw as pdfium_c

# Docling renders page images at this scale (2.0 = 144 DPI); its crops are the fallback.
DOCLING_IMAGES_SCALE = 2.0
# PDF pictures that are not pure vector are rendered from the PDF at the resolution
# of their densest embedded image, within these limits. Regions without embedded
# images (vector content that pdftocairo cannot express as pure SVG) use VECTOR_RENDER_DPI.
MIN_RENDER_DPI = 72 * DOCLING_IMAGES_SCALE
MAX_RENDER_DPI = 600
VECTOR_RENDER_DPI = 300
MAX_RENDER_PIXELS = 40_000_000

SUPPORTED = {'.pdf', '.docx', '.pptx', '.xlsx', '.xlsm', '.md', '.pages', '.numbers', '.key'}
IWORK = {'.pages': 'Pages', '.numbers': 'Numbers', '.key': 'Keynote'}
OFFICE = {'.docx', '.pptx', '.xlsx', '.xlsm'}
# Single numbered references; ranges/lists and bare parenthetical equation
# numbers deliberately aren't inferred.
MENTION = re.compile(
    r'\b(?P<label>fig(?:ure)?s?\.?|charts?|graphs?|tables?|eq(?:uation)?s?\.?)'
    r'\s*\(?\s*(?P<number>\d+(?:\.\d+)*[A-Za-z]?)\s*\)?', re.IGNORECASE
)


class ExtractionError(RuntimeError):
    """Conversion, export, or output failure."""


def _value(value: Any) -> str:
    return str(getattr(value, 'value', value))


def _json(value: Any) -> Any:
    if hasattr(value, 'model_dump'):
        return value.model_dump(mode='json', by_alias=True, exclude_none=True)
    return value


def _refs(item: Any, field: str) -> list[str]:
    return [ref.cref for ref in getattr(item, field, [])]


def _reference_key(match: re.Match) -> tuple[str, str]:
    label = match['label'].lower()
    family = ('table' if label.startswith('tab') else
              'equation' if label.startswith('eq') else 'figure')
    return family, match['number'].lower()


def _pure_vector_svg(path: Path) -> bool:
    content = path.read_bytes()
    if re.search(rb'data:image/(?:png|jpe?g|gif|webp|bmp)', content, re.IGNORECASE):
        return False
    try:
        root = ET.fromstring(content)
    except ET.ParseError as exc:
        raise ExtractionError(f'Invalid SVG generated by pdftocairo: {exc}') from exc
    if root.tag != '{http://www.w3.org/2000/svg}svg':
        raise ExtractionError('pdftocairo generated a document without an SVG root')
    return not any(isinstance(elem.tag, str) and elem.tag.split('}')[-1].lower() == 'image'
                   for elem in root.iter())


def _picture_region(pdf: Any, document: Any, prov: Any) -> tuple[Any, Any, float, float, tuple[float, ...], tuple[float, ...]]:
    """Open the page of a Docling region and locate the region on it.

    Returns the page (the caller closes it), the region's box in displayed
    top-left coordinates, the displayed page size, and the x and y coordinates
    of the region's corners in PDF user space.
    """
    page_index = prov.page_no - 1
    if page_index < 0 or page_index >= len(pdf) or prov.page_no not in document.pages:
        raise ExtractionError(f'Invalid page number {prov.page_no}')
    page = pdf[page_index]
    try:
        width, height = page.get_size()
        doc_size = document.pages[prov.page_no].size
        if not (math.isclose(width, doc_size.width, abs_tol=0.1) and
                math.isclose(height, doc_size.height, abs_tol=0.1)):
            raise ExtractionError(f'Docling and PDF page dimensions differ on page {prov.page_no}')
        box = prov.bbox.to_top_left_origin(height)
        if not (0 <= box.l < box.r <= width and 0 <= box.t < box.b <= height):
            raise ExtractionError(f'Picture bounding box is outside page {prov.page_no}')
        left, bottom, right, top = page.get_bbox()
        rotation = page.get_rotation()
        def page_point(x: float, y: float) -> tuple[float, float]:
            if rotation == 0:
                return left + x, top - y
            if rotation == 90:
                return left + y, bottom + x
            if rotation == 180:
                return right - x, bottom + y
            if rotation == 270:
                return right - y, top - x
            raise ExtractionError(f'Unsupported PDF rotation {rotation}')
        points = [page_point(x, y) for x in (box.l, box.r) for y in (box.t, box.b)]
        xs, ys = zip(*points)
    except BaseException:
        page.close()
        raise
    return page, box, width, height, xs, ys


def _image_density(page: Any, region: tuple[float, float, float, float]) -> float | None:
    """Return the highest pixels-per-point of embedded images overlapping a user-space region.

    Images inside form XObjects are placed by composing each form's matrix, since
    pdfium reports a nested object's matrix in its form's coordinate space.
    """
    x0, y0, x1, y1 = region
    densest = None

    def compose(m, n):  # apply m, then n (PDF row-vector convention)
        a1, b1, c1, d1, e1, f1 = m
        a2, b2, c2, d2, e2, f2 = n
        return (a1 * a2 + b1 * c2, a1 * b2 + b1 * d2, c1 * a2 + d1 * c2,
                c1 * b2 + d1 * d2, e1 * a2 + f1 * c2 + e2, e1 * b2 + f1 * d2 + f2)

    def walk(handles, parent, depth):
        nonlocal densest
        for handle in handles:
            raw = pdfium_c.FS_MATRIX()
            if not pdfium_c.FPDFPageObj_GetMatrix(handle, raw):
                continue
            matrix = compose((raw.a, raw.b, raw.c, raw.d, raw.e, raw.f), parent)
            kind = pdfium_c.FPDFPageObj_GetType(handle)
            if kind == pdfium_c.FPDF_PAGEOBJ_FORM and depth < 16:
                count = pdfium_c.FPDFFormObj_CountObjects(handle)
                walk((pdfium_c.FPDFFormObj_GetObject(handle, i) for i in range(count)),
                     matrix, depth + 1)
            elif kind == pdfium_c.FPDF_PAGEOBJ_IMAGE:
                pw, ph = ctypes.c_uint(), ctypes.c_uint()
                if not pdfium_c.FPDFImageObj_GetImagePixelSize(handle, ctypes.byref(pw), ctypes.byref(ph)):
                    continue
                a, b, c, d, e, f = matrix
                corners = [(e + u * a + v * c, f + u * b + v * d) for u in (0, 1) for v in (0, 1)]
                cx, cy = zip(*corners)
                if min(cx) >= x1 or max(cx) <= x0 or min(cy) >= y1 or max(cy) <= y0:
                    continue
                # The image's unit square maps to vectors (a, b) and (c, d) in points.
                x_extent, y_extent = math.hypot(a, b), math.hypot(c, d)
                if x_extent and y_extent:
                    density = max(pw.value / x_extent, ph.value / y_extent)
                    densest = density if densest is None else max(densest, density)

    count = pdfium_c.FPDFPage_CountObjects(page.raw)
    walk((pdfium_c.FPDFPage_GetObject(page.raw, i) for i in range(count)), (1, 0, 0, 1, 0, 0), 0)
    return densest


def _render_region(pdf: Any, document: Any, prov: Any, output: Path) -> float:
    """Render a Docling region from the PDF at its native resolution; return the DPI used.

    Regions containing images render at the densest image's resolution; pure
    vector or text regions (formulas, most tables) at VECTOR_RENDER_DPI. The page
    is drawn as a viewer shows it, so transparent images are composited over the
    white page and anything drawn over them is included.
    """
    page, box, width, height, xs, ys = _picture_region(pdf, document, prov)
    try:
        density = _image_density(page, (min(xs), min(ys), max(xs), max(ys)))
        dpi = density * 72 if density else VECTOR_RENDER_DPI
        dpi = min(max(dpi, MIN_RENDER_DPI), MAX_RENDER_DPI)
        pixels = (box.r - box.l) * (box.b - box.t) * (dpi / 72) ** 2
        if pixels > MAX_RENDER_PIXELS:
            dpi *= math.sqrt(MAX_RENDER_PIXELS / pixels)
        bitmap = page.render(scale=dpi / 72, crop=(box.l, height - box.b, width - box.r, box.t))
        try:
            bitmap.to_pil().convert('RGB').save(output, format='PNG')
        finally:
            bitmap.close()
        return dpi
    finally:
        page.close()


def _extract_picture_svg(pdf: Any, document: Any, prov: Any, output: Path) -> bool:
    """Convert a Docling picture region in displayed page coordinates to SVG."""
    page, _, _, _, xs, ys = _picture_region(pdf, document, prov)
    page_index = prov.page_no - 1
    try:
        with tempfile.TemporaryDirectory(prefix='docling-svg-') as temporary:
            cropped = pdfium.PdfDocument.new()
            try:
                cropped.import_pages(pdf, pages=[page_index])
                cropped_page = cropped[0]
                try:
                    cropped_page.set_cropbox(min(xs), min(ys), max(xs), max(ys))
                finally:
                    cropped_page.close()
                pdf_path = Path(temporary) / 'crop.pdf'
                svg_path = Path(temporary) / 'crop.svg'
                cropped.save(pdf_path)
                subprocess.run(['pdftocairo', '-svg', str(pdf_path), str(svg_path)],
                               check=True, capture_output=True)
                if not _pure_vector_svg(svg_path):
                    return False
                output.write_bytes(svg_path.read_bytes())
                return True
            finally:
                cropped.close()
    finally:
        page.close()


def _build_manifest(document: Any, directory: Path, pdf_path: Path | None = None) -> dict[str, Any]:
    if pdf_path is None:
        return _build_manifest_for_pdf(document, directory, None)
    try:
        pdf = pdfium.PdfDocument(pdf_path)
    except pdfium.PdfiumError as exc:
        manifest = _build_manifest_for_pdf(document, directory, None)
        manifest['warnings'].insert(0, f'PDF vector extraction unavailable: {exc}')
        return manifest
    try:
        return _build_manifest_for_pdf(document, directory, pdf)
    finally:
        pdf.close()


def _build_manifest_for_pdf(document: Any, directory: Path, pdf: Any) -> dict[str, Any]:
    from docling_core.types.doc.items.picture.picture import PictureItem
    from docling_core.types.doc.items.table.table import TableItem
    from docling_core.types.doc.items.text import TextItem

    elements: list[dict[str, Any]] = []
    source_texts: list[dict[str, Any]] = []
    order: list[dict[str, Any]] = []
    warnings: list[str] = []
    asset_dir = directory / 'assets'
    asset_dir.mkdir()
    # include captions and text nested inside figures, not just top-level text
    for item, level in document.iterate_items(traverse_pictures=True):
        label = _value(getattr(item, 'label', ''))
        is_formula = label == 'formula'
        is_element = isinstance(item, (PictureItem, TableItem)) or is_formula
        record = {
            'id': item.self_ref, 'label': label, 'level': level,
            'parent_ref': getattr(getattr(item, 'parent', None), 'cref', None),
            'provenance': [_json(p) for p in getattr(item, 'prov', [])],
            'source': _json(getattr(item, 'source', None)),
            'metadata': _json(getattr(item, 'meta', None)),
        }
        if is_element:
            kind = ('picture' if isinstance(item, PictureItem) else
                    'table' if isinstance(item, TableItem) else 'formula')
            record.update(kind=kind, asset=None, caption_refs=_refs(item, 'captions'),
                          reference_refs=_refs(item, 'references'),
                          footnote_refs=_refs(item, 'footnotes'),
                          annotations=[_json(a) for a in getattr(item, 'annotations', [])],
                          text=getattr(item, 'text', None))
            if isinstance(item, TableItem):
                record['data'] = _json(item.data)
            images = []
            raster_assets = []
            # Preserve crops for each provenance region, e.g. multipage tables.
            for prov_index in range(max(1, len(getattr(item, 'prov', [])))):
                raster_path = None
                try:
                    image = item.get_image(document, prov_index=prov_index)
                    if image is not None:
                        path = asset_dir / f'{kind}-{len(elements)+1:04d}-{prov_index+1}.png'
                        image.save(path, format='PNG')
                        raster_path = path.relative_to(directory).as_posix()
                except Exception as exc:
                    warnings.append(f'Image unavailable for {item.self_ref} '
                                    f'region {prov_index}: {type(exc).__name__}')
                in_pdf = pdf is not None and prov_index < len(getattr(item, 'prov', []))
                if kind == 'picture' and in_pdf:
                    svg_path = asset_dir / f'{kind}-{len(elements)+1:04d}-{prov_index+1}.svg'
                    try:
                        if _extract_picture_svg(pdf, document, item.prov[prov_index], svg_path):
                            images.append(svg_path.relative_to(directory).as_posix())
                            raster_assets.append(raster_path)
                            continue
                    except (ExtractionError, OSError, subprocess.SubprocessError, pdfium.PdfiumError) as exc:
                        warnings.append(f'SVG extraction unavailable for {item.self_ref} '
                                        f'region {prov_index}: {exc}')
                elif kind == 'picture' and pdf is not None:
                    warnings.append(f'SVG extraction unavailable for {item.self_ref}: no provenance.')
                if in_pdf:
                    # Pictures that are not pure vector, formulas and tables: render the
                    # region from the PDF at full resolution instead of using Docling's
                    # DOCLING_IMAGES_SCALE page crop.
                    png_path = asset_dir / f'{kind}-{len(elements)+1:04d}-{prov_index+1}-full.png'
                    try:
                        _render_region(pdf, document, item.prov[prov_index], png_path)
                        rendered = png_path.relative_to(directory).as_posix()
                        images.append(rendered)
                        raster_assets.append(rendered)
                        continue
                    except (ExtractionError, OSError, ValueError, pdfium.PdfiumError) as exc:
                        warnings.append(f'Full-resolution rendering unavailable for {item.self_ref} '
                                        f'region {prov_index}: {exc}')
                if raster_path is not None:
                    images.append(raster_path)
                    raster_assets.append(raster_path)
            record['assets'] = images
            record['raster_assets'] = raster_assets
            record['asset'] = images[0] if images else None
            if not images:
                warnings.append(f'No image crop available for {item.self_ref}.')
            elements.append(record)
        if isinstance(item, TextItem):
            text_record = {**record, 'text': item.text, 'original_text': item.orig,
                           'mentions': [], 'element_refs': []}
            source_texts.append(text_record)
        order.append({'id': item.self_ref, 'label': label,
                      'text': getattr(item, 'text', None), 'is_element': is_element})

    # Explicit structural links also run in reverse from captions/references.
    reverse: dict[str, list[str]] = {}
    for element in elements:
        for field in ('caption_refs', 'reference_refs', 'footnote_refs'):
            for ref in element[field]:
                reverse.setdefault(ref, []).append(element['id'])
    text_by_id = {text['id']: text for text in source_texts}
    targets: dict[tuple[str, str], list[str]] = {}
    for element in elements:
        captions = [text_by_id[r]['text'] for r in element['caption_refs'] if r in text_by_id]
        if element['kind'] == 'formula' and element['text']:
            captions.append(element['text'])
        for caption in captions:
            for match in MENTION.finditer(caption):
                # Only labels at the start of a caption can name this element.
                if caption[:match.start()].strip():
                    continue
                key = _reference_key(match)
                if ((key[0] == 'table' and element['kind'] == 'table') or
                    (key[0] == 'equation' and element['kind'] == 'formula') or
                    (key[0] == 'figure' and element['kind'] == 'picture')):
                    values = targets.setdefault(key, [])
                    if element['id'] not in values:
                        values.append(element['id'])
    for text in source_texts:
        text['element_refs'] = list(dict.fromkeys(reverse.get(text['id'], [])))
        for match in MENTION.finditer(text['text']):
            candidates = targets.get(_reference_key(match), [])
            text['mentions'].append({
                'literal': match.group(), 'span': [match.start(), match.end()],
                'candidate_element_refs': candidates,
                'element_ref': candidates[0] if len(candidates) == 1 else None,
                'method': 'numbered_label_heuristic',
                'resolution': 'unique' if len(candidates) == 1 else
                              'ambiguous' if candidates else 'unresolved',
            })
    lines = []
    for node in order:
        if node['is_element']:
            lines.append(f"[ELEMENT {node['id']} label={node['label']}]")
        if node['text']:
            lines.append(node['text'])
    return {'elements': elements, 'source_texts': source_texts,
            'reading_order': order, 'linked_text': '\n\n'.join(lines),
            'warnings': warnings}


def extract_document(
    source: str | Path | bytes | BinaryIO,
    *,
    output_dir: str | Path,
    filename: str | None = None,
    service_url: str | None = None,
    api_key: str | None = None,
    pdf_exporter: Callable[[Path, Path], Path] | None = None,
    render_office: bool = False,
    native_iwork: bool = True,
    describe_pictures: bool = True,
    extract_chart_data: bool = True,
    enrich_formulas: bool = True,
    allow_partial: bool = False,
    timeout: float = 600,
    service_options: dict[str, Any] | None = None,
    client: Any = None,
) -> dict[str, Any]:
    """Upload one document and return text, elements, assets and references.

    A supplied client implements convert(source=Path, options=..., raises_on_error
    =False). It remains open and is useful for connection reuse and testing.
    Otherwise this function owns/closes an official DoclingServiceClient.
    service_options can select model presets and override enrichment defaults;
    JSON output and referenced image export remain required, unless
    DOCLING_IMAGE_EXPORT_MODE=embedded is set for servers without artifact storage.
    The service client materializes the image resource bundle before returning the document.
    Set allow_partial explicitly
    to retain incomplete conversions. Failures raise ExtractionError; no successful
    manifest is written for a failed conversion.
    """
    from docling.datamodel.service.options import ConvertDocumentsOptions
    from docling.service_client import DoclingServiceClient, StatusWatcherKind
    from docling_core.types.doc.base import ImageRefMode

    if timeout <= 0:
        raise ValueError('timeout must be positive')
    if isinstance(source, (str, Path)):
        original = Path(source).expanduser().resolve()
        source_name = original.name
        if not original.exists():
            raise FileNotFoundError(original)
        if original.is_dir() and original.suffix.lower() not in IWORK:
            raise ValueError('Only iWork package directories are accepted')
    else:
        if not filename:
            raise ValueError('filename is required for bytes or binary streams')
        source_name = Path(filename).name
        original = None
    suffix = Path(source_name).suffix.lower()
    if suffix not in SUPPORTED:
        raise ValueError(f'Unsupported extension {suffix!r}; expected {sorted(SUPPORTED)}')
    service_url = service_url or os.environ.get('DOCLING_SERVICE_URL')
    api_key = api_key if api_key is not None else os.environ.get('DOCLING_SERVICE_API_KEY', '')
    if client is None and not service_url:
        raise ValueError('Supply service_url or set DOCLING_SERVICE_URL')
    root = Path(output_dir).expanduser().resolve()
    run_dir = root / f'extraction-{uuid4().hex}'
    run_dir.mkdir(parents=True)
    opts = {'do_ocr': True, 'do_table_structure': True, 'include_images': True,
            'include_page_images': True, 'images_scale': DOCLING_IMAGES_SCALE,
            'do_formula_enrichment': enrich_formulas,
            'do_picture_classification': True,
            'do_picture_description': describe_pictures,
            'do_chart_extraction': extract_chart_data}
    opts.update(service_options or {})
    # Servers without artifact storage (e.g. a local docling-serve) return the
    # document in the response body, where referenced images are lost; use embedded.
    image_mode = os.environ.get('DOCLING_IMAGE_EXPORT_MODE', 'referenced')
    if image_mode not in ('referenced', 'embedded'):
        raise ValueError('DOCLING_IMAGE_EXPORT_MODE must be referenced or embedded')
    opts.update(to_formats=['json'], image_export_mode=image_mode, include_images=True)
    options = ConvertDocumentsOptions(**opts)
    warnings = []
    with tempfile.TemporaryDirectory(prefix='docling-input-') as temporary:
        temp = Path(temporary)
        if original is None:
            original = temp / ('input' + suffix)
            content = source if isinstance(source, bytes) else source.read()
            if not isinstance(content, bytes):
                raise TypeError('source must be bytes or a binary stream')
            original.write_bytes(content)
        prepared = original
        needs_pdf = (suffix in IWORK and not native_iwork) or (
            suffix in OFFICE and render_office)
        if needs_pdf:
            exporter = pdf_exporter
            if exporter is None:
                raise ValueError('PDF conversion requires a pdf_exporter callback')
            prepared = Path(exporter(original, temp / 'export.pdf')).resolve()
            if not prepared.is_file() or prepared.suffix.lower() != '.pdf':
                raise ExtractionError('pdf_exporter must return an existing PDF path')
            with prepared.open('rb') as file:
                if not file.read(1024).lstrip().startswith(b'%PDF-'):
                    raise ExtractionError('pdf_exporter output is not a PDF')
            warnings.append('Provenance refers to the exported PDF; original '
                            'pagination/sheet layout may differ.')
        elif suffix in OFFICE:
            warnings.append('Native Office conversion may omit vector drawings, '
                            'charts or visual math. For visual coverage use '
                            'render_office=True with a PDF exporter.')
        if prepared.is_dir():
            raise ExtractionError('Native upload requires a single iWork file; '
                                  'export this package directory to PDF instead.')
        digest = hashlib.sha256()
        with prepared.open('rb') as file:
            for chunk in iter(lambda: file.read(1024 * 1024), b''):
                digest.update(chunk)
        owned_client = client is None
        if owned_client:
            client = DoclingServiceClient(url=service_url, api_key=api_key,
                                           job_timeout=timeout, status_watcher=StatusWatcherKind.POLLING)
        try:
            conversion = client.convert(source=prepared, options=options, raises_on_error=False)
        finally:
            if owned_client:
                client.close()
        status = _value(conversion.status)
        if status != 'success' and not (allow_partial and status == 'partial_success'):
            raise ExtractionError(f'Docling conversion status: {status}; '
                                  f'errors: {conversion.errors}')
        document = conversion.document
        manifest = _build_manifest(document, run_dir, prepared if prepared.suffix.lower() == '.pdf' else None)
        manifest.update(schema_version='1.0', source_filename=source_name,
                        processed_format=prepared.suffix.lower().lstrip('.'),
                        processed_sha256=digest.hexdigest(), status=status,
                        errors=[_json(e) for e in conversion.errors],
                        output_directory=str(run_dir),
                        docling_document='document.json', text_file='source_text.txt')
        manifest['warnings'] = warnings + manifest['warnings']
